const DAY = 864e5;
const iso = (date) => `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
// Дата, у которой день и месяц наступят через inDays дней, а год — yearsAgo лет назад от того дня.
// Так ближайшие даты и обратный отсчёт до праздника выглядят одинаково, когда бы демо ни запустили.
function anniversary(now, inDays, yearsAgo) {
  const day = new Date(now.getFullYear(), now.getMonth(), now.getDate() + inDays);
  return new Date(day.getFullYear() - yearsAgo, day.getMonth(), day.getDate());
}

